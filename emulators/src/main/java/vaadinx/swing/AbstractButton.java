    /**
     * Action.NAME → button text, in the JDK's two shapes.
     *
     * <p>Named and split as {@code javax.swing.AbstractButton.setTextFromAction}
     * is, because collapsing the two branches into the {@code propertyChange}
     * one — as this did — makes a full reconfigure decline to *clear* stale text
     * instead of clearing it. {@code hideActionText} is the toolbar idiom: show
     * the Action's name as the tooltip, not as the visible label.
     *
     * @param propertyChange {@code true} when responding to the Action's own NAME
     *     property changing (leave the text alone while hidden), {@code false} for
     *     a full reconfigure (null the text while hidden).
     */
    private void setTextFromAction(javax.swing.Action a, boolean propertyChange) {
        boolean hideText = getHideActionText();
        if (!propertyChange) {
            setText(a != null && !hideText ? (String) a.getValue(javax.swing.Action.NAME) : null);
        } else if (!hideText) {
            setText((String) a.getValue(javax.swing.Action.NAME));
        }
    }

