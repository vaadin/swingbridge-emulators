    protected void actionPropertyChanged(javax.swing.Action a, java.lang.String propertyName) {
        // Route per-property updates back through the same helpers
        // configurePropertiesFromAction uses. JDK passes interned strings
        // for the keys (Action.NAME, "enabled", …) so identity comparison
        // is safe and saves the equals cost on the hot path.
        if (propertyName == javax.swing.Action.NAME) {
            setTextFromAction(a, true);
        } else if ("enabled".equals(propertyName)) {
            setEnabled(a.isEnabled());
        } else if (propertyName == javax.swing.Action.SHORT_DESCRIPTION) {
            setToolTipTextFromAction(a);
        } else if (propertyName == javax.swing.Action.SMALL_ICON
                || propertyName == javax.swing.Action.LARGE_ICON_KEY) {
            setIconFromAction(a);
        } else if (propertyName == javax.swing.Action.ACTION_COMMAND_KEY) {
            setActionCommandFromAction(a);
        } else if (propertyName == javax.swing.Action.MNEMONIC_KEY) {
            setMnemonicFromAction(a);
            // Mnemonic index may clamp on the new text length; re-evaluate
            // so a mnemonic change doesn't leave stale index state.
            setDisplayedMnemonicIndexFromAction(a);
        } else if (propertyName == javax.swing.Action.DISPLAYED_MNEMONIC_INDEX_KEY) {
            setDisplayedMnemonicIndexFromAction(a);
        }
        // Unknown keys: JDK silently drops. We follow — user code adding
        // arbitrary Action.putValue("foo", bar) entries has no button
        // semantic and shouldn't trip a WARN.
    }

