    /**
     * Fires an ANCESTOR_ADDED / ANCESTOR_REMOVED to currently-stored
     * {@link vaadinx.swing.event.AncestorListener}s. Short-circuits when
     * nobody's listening — same pattern as Component's fire* helpers.
     * ANCESTOR_MOVED is not fired (Vaadin has no server-side
     * layout-position event); same accepted incompleteness as the
     * surrogate-side wiring in {@code JComponentMixin.addAncestorListener}.
     */
    private void fireAncestorEvent(int id) {
        if (listenerList.getListenerCount(vaadinx.swing.event.AncestorListener.class) == 0) return;
        // ancestor = self for direct attach/detach (matches the
        // surrogate-side SAncestorEvent wiring); ancestorParent = current
        // parent. On detach, Container.remove sets parent=null *after*
        // peer.removeFromParent (which triggers our DetachListener), so
        // by the time this fires the field is still set to the old
        // parent — useful for listeners that need to know which container
        // they're leaving.
        vaadinx.swing.event.AncestorEvent e = new vaadinx.swing.event.AncestorEvent(
                this, id, this, getParent());
        for (vaadinx.swing.event.AncestorListener l :
                listenerList.getListeners(vaadinx.swing.event.AncestorListener.class)) {
            if (id == vaadinx.swing.event.AncestorEvent.ANCESTOR_ADDED) {
                l.ancestorAdded(e);
            } else if (id == vaadinx.swing.event.AncestorEvent.ANCESTOR_REMOVED) {
                l.ancestorRemoved(e);
            }
        }
    }

