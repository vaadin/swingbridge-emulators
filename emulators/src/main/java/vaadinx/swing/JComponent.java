    public void registerKeyboardAction(java.awt.event.ActionListener listener,
                                       javax.swing.KeyStroke stroke,
                                       int condition) {
        registerKeyboardAction(listener, null, stroke, condition);
    }

    public void registerKeyboardAction(java.awt.event.ActionListener listener,
                                       java.lang.String command,
                                       javax.swing.KeyStroke stroke,
                                       int condition) {
        // JDK shape: wrap the listener in an ActionStandin so the same
        // Action object can serve as both the InputMap value (identifier)
        // and the ActionMap key+value. User code that reads back the
        // ActionMap sees a real Action it can invoke, including on
        // mnemonic paths.
        javax.swing.InputMap im = getInputMap(condition);
        javax.swing.ActionMap am = getActionMap();
        ActionStandin action = new ActionStandin(listener, command);
        im.put(stroke, action);
        am.put(action, action);
        installVaadinShortcut(condition, stroke, action);
    }

    public void unregisterKeyboardAction(javax.swing.KeyStroke stroke) {
        // JDK removes across every condition. We mirror: walk all three
        // InputMaps, drop the stroke (and its ActionMap entry by
        // identifier), uninstall the matching Vaadin shortcut.
        for (int condition : new int[]{WHEN_FOCUSED, WHEN_ANCESTOR_OF_FOCUSED_COMPONENT, WHEN_IN_FOCUSED_WINDOW}) {
            javax.swing.InputMap im = rawInputMap(condition);
            if (im == null) continue;
            Object key = im.get(stroke);
            if (key == null) continue;
            im.remove(stroke);
            if (actionMap != null) actionMap.remove(key);
            uninstallShortcut(condition, stroke);
        }
    }

    public javax.swing.KeyStroke[] getRegisteredKeyStrokes() {
        // Union of strokes registered across all three conditions. Order
        // matches the InputMap walk (focused/ancestor/window); JDK makes
        // no ordering promise so any stable order is fine.
        java.util.LinkedHashSet<javax.swing.KeyStroke> strokes = new java.util.LinkedHashSet<>();
        for (int condition : new int[]{WHEN_FOCUSED, WHEN_ANCESTOR_OF_FOCUSED_COMPONENT, WHEN_IN_FOCUSED_WINDOW}) {
            javax.swing.InputMap im = rawInputMap(condition);
            if (im == null) continue;
            javax.swing.KeyStroke[] keys = im.allKeys();
            if (keys != null) {
                java.util.Collections.addAll(strokes, keys);
            }
        }
        return strokes.toArray(new javax.swing.KeyStroke[0]);
    }

    public int getConditionForKeyStroke(javax.swing.KeyStroke stroke) {
        // JDK returns UNDEFINED_CONDITION (-1) when the stroke isn't
        // bound. Walk in the order JDK documents: focused first, then
        // ancestor, then window.
        if (focusedInputMap != null && focusedInputMap.get(stroke) != null) return WHEN_FOCUSED;
        if (ancestorInputMap != null && ancestorInputMap.get(stroke) != null) return WHEN_ANCESTOR_OF_FOCUSED_COMPONENT;
        if (windowInputMap != null && windowInputMap.get(stroke) != null) return WHEN_IN_FOCUSED_WINDOW;
        return UNDEFINED_CONDITION;
    }

    public java.awt.event.ActionListener getActionForKeyStroke(javax.swing.KeyStroke stroke) {
        // Resolve InputMap → action key → ActionMap → Action. JDK returns
        // null when the stroke isn't bound OR when the ActionMap has no
        // entry for the key — we match both.
        if (actionMap == null) return null;
        for (int condition : new int[]{WHEN_FOCUSED, WHEN_ANCESTOR_OF_FOCUSED_COMPONENT, WHEN_IN_FOCUSED_WINDOW}) {
            javax.swing.InputMap im = rawInputMap(condition);
            if (im == null) continue;
            Object key = im.get(stroke);
            if (key != null) {
                return actionMap.get(key);
            }
        }
        return null;
    }

    public void resetKeyboardActions() {
        // Clear every condition's map + uninstall every Vaadin shortcut.
        // Field-null each InputMap rather than calling .clear(): the map
        // might be shared with a parent (JDK allows InputMap.setParent),
        // in which case clearing mutates the parent too.
        if (installedShortcuts != null) {
            java.util.List<com.vaadin.flow.component.ShortcutRegistration> regs =
                    new java.util.ArrayList<>(installedShortcuts.values());
            withPeer(p -> regs.forEach(com.vaadin.flow.component.ShortcutRegistration::remove));
            installedShortcuts.clear();
        }
        if (focusedInputMap != null) focusedInputMap.clear();
        if (ancestorInputMap != null) ancestorInputMap.clear();
        if (windowInputMap != null) windowInputMap.clear();
        if (actionMap != null) actionMap.clear();
    }

    /**
     * Raw accessor (no lazy allocation) — used by query paths so calling
     * {@code getConditionForKeyStroke} on a fresh component doesn't
     * materialise three empty InputMaps.
     */
    private javax.swing.InputMap rawInputMap(int condition) {
        return switch (condition) {
            case WHEN_FOCUSED -> focusedInputMap;
            case WHEN_ANCESTOR_OF_FOCUSED_COMPONENT -> ancestorInputMap;
            case WHEN_IN_FOCUSED_WINDOW -> windowInputMap;
            default -> null;
        };
    }

    /**
     * Install a Vaadin {@code Shortcuts} registration that routes a
     * browser key press through {@link EHelper#callSwing} back to the
     * Action's {@code actionPerformed}. Scope per condition:
     *
     * <ul>
     *   <li>{@link #WHEN_IN_FOCUSED_WINDOW} — no {@code listenOn}, so
     *       Vaadin scopes at the UI (≈ window for our single-UI model).</li>
     *   <li>{@link #WHEN_FOCUSED} / {@link #WHEN_ANCESTOR_OF_FOCUSED_COMPONENT}
     *       — {@code listenOn(peer)} so the key only fires when focus is
     *       within this component's peer subtree.</li>
     * </ul>
     *
     * <p>Unmappable {@code KeyStroke}s (punctuation, numpad, …) log an
     * onUnimplemented and skip the browser-side install. The InputMap +
     * ActionMap entries still land so {@code getActionForKeyStroke}
     * returns the Action — server-driven code paths (programmatic key
     * lookup, tests) keep working even when the browser wire-up can't.
     */
    private void installVaadinShortcut(int condition, javax.swing.KeyStroke stroke,
                                       final ActionStandin action) {
        com.vaadin.swingbridge.surrogates.util.KeyConvert.VaadinKeyBinding binding = com.vaadin.swingbridge.surrogates.util.KeyConvert.toVaadinKeyBinding(stroke);
        if (binding == null) {
            vaadinx.EHelper.onUnimplemented("JComponent", "registerKeyboardAction/unmappable-keystroke", stroke);
            return;
        }
        final vaadinx.awt.Component source = this;
        // Vaadin's Shortcuts API takes a Command (SerializableRunnable),
        // not a plain Runnable — declare the type explicitly so the
        // lambda targets the correct functional interface.
        com.vaadin.flow.server.Command command = () -> vaadinx.EHelper.callSwing(() -> {
            java.awt.event.ActionEvent e = new java.awt.event.ActionEvent(
                    source,
                    java.awt.event.ActionEvent.ACTION_PERFORMED,
                    action.command());
            action.actionPerformed(e);
        });
        com.vaadin.flow.component.ShortcutRegistration[] registered = new com.vaadin.flow.component.ShortcutRegistration[1];
        withPeer(p -> {
            registered[0] = com.vaadin.flow.component.Shortcuts.addShortcutListener(
                    p, command, binding.key(), binding.modifiers());
            if (condition != WHEN_IN_FOCUSED_WINDOW) {
                // Scope to this component's subtree — key only fires when
                // focus is within the peer. Best-effort match to Swing's
                // WHEN_FOCUSED / WHEN_ANCESTOR_OF_FOCUSED_COMPONENT.
                registered[0].listenOn(p);
            }
        });
        com.vaadin.flow.component.ShortcutRegistration reg = registered[0];
        if (installedShortcuts == null) installedShortcuts = new java.util.LinkedHashMap<>();
        ShortcutKey key = new ShortcutKey(condition, stroke);
        com.vaadin.flow.component.ShortcutRegistration previous = installedShortcuts.put(key, reg);
        if (previous != null) withPeer(p -> previous.remove());
    }

    /** Remove the Vaadin shortcut for a specific (condition, stroke). */
    private void uninstallShortcut(int condition, javax.swing.KeyStroke stroke) {
        if (installedShortcuts == null) return;
        com.vaadin.flow.component.ShortcutRegistration reg =
                installedShortcuts.remove(new ShortcutKey(condition, stroke));
        if (reg != null) withPeer(p -> reg.remove());
    }

    /**
     * {@link javax.swing.Action} adapter that wraps a plain
     * {@link java.awt.event.ActionListener} plus the optional command
     * string passed to {@code registerKeyboardAction}. Single object
     * serves as InputMap value, ActionMap key, and ActionMap value —
     * matches JDK's {@code ActionStandin} pattern.
     */
    private static final class ActionStandin extends javax.swing.AbstractAction {
        private final java.awt.event.ActionListener listener;
        private final String command;

        ActionStandin(java.awt.event.ActionListener listener, String command) {
            this.listener = listener;
            this.command = command;
        }

        String command() {
            return command;
        }

        @Override
        public void actionPerformed(java.awt.event.ActionEvent e) {
            // JDK re-sources the event if the command differs. We pass
            // the event through — the caller above already built an
            // event with the correct source + command.
            listener.actionPerformed(e);
        }
    }

    public final void setInputMap(int condition, javax.swing.InputMap map) {
        // Replacing the InputMap tears down every Vaadin shortcut we'd
        // installed for strokes under this condition — the replacement
        // may not carry them forward, and stale shortcuts would fire on
        // keys the InputMap no longer binds.
        uninstallShortcutsForCondition(condition);
        switch (condition) {
            case WHEN_FOCUSED -> focusedInputMap = map;
            case WHEN_ANCESTOR_OF_FOCUSED_COMPONENT -> ancestorInputMap = map;
            case WHEN_IN_FOCUSED_WINDOW -> windowInputMap = map;
            default -> throw new IllegalArgumentException(
                    "condition must be one of WHEN_FOCUSED, WHEN_ANCESTOR_OF_FOCUSED_COMPONENT, WHEN_IN_FOCUSED_WINDOW");
        }
    }

    public final void setActionMap(javax.swing.ActionMap map) {
        this.actionMap = map;
    }

    /**
     * Remove every Vaadin shortcut we installed for the given condition.
     * Used by {@link #setInputMap} when the replacement InputMap may not
     * carry the previous bindings. No-op when no shortcuts were ever
     * installed (common case).
     */
    private void uninstallShortcutsForCondition(int condition) {
        if (installedShortcuts == null) return;
        java.util.Iterator<java.util.Map.Entry<ShortcutKey, com.vaadin.flow.component.ShortcutRegistration>> it =
                installedShortcuts.entrySet().iterator();
        while (it.hasNext()) {
            java.util.Map.Entry<ShortcutKey, com.vaadin.flow.component.ShortcutRegistration> e = it.next();
            if (e.getKey().condition() == condition) {
                com.vaadin.flow.component.ShortcutRegistration reg = e.getValue();
                withPeer(p -> reg.remove());
                it.remove();
            }
        }
    }

