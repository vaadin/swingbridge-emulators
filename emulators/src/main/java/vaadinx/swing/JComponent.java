    public void setBorder(vaadinx.swing.border.Border newBorder) {
        // AbstractBorder subclasses carry their own CSS via
        // applyCss; custom user borders that extend Border directly don't
        // render (R_best_effort_behaviour best-effort) but still round-trip through
        // getBorder and contribute their insets to getInsets. Matches
        // the JDK shape of storing the field and firing the "border" PCE.
        vaadinx.swing.border.Border old = this.border;
        if (java.util.Objects.equals(old, newBorder)) return;
        this.border = newBorder;
        if (newBorder instanceof vaadinx.swing.border.AbstractBorder ab) {
            withPeer(p -> ab.applyCss(p.getElement()));
        } else {
            // Null or custom non-AbstractBorder: strip any previously-
            // written CSS so the old border doesn't linger. A custom
            // Border's visual rendering is a deferred gap (no applyCss
            // extension point exposed publicly yet); log once so
            // migrations with custom borders surface the drop.
            withPeer(p -> vaadinx.swing.border.AbstractBorder.clearBorderCss(p.getElement()));
            if (newBorder != null) {
                vaadinx.EHelper.onUnimplemented("JComponent", "setBorder/custom-Border-impl", newBorder);
            }
        }
        firePropertyChange("border", old, newBorder);
    }

