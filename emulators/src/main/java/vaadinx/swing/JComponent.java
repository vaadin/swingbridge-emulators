    public void setInputVerifier(vaadinx.swing.InputVerifier newVerifier) {
        // Wires through the peer's blur listener when the peer is a
        // BlurNotifier (most input peers — TextField, Button, Checkbox,
        // … — are). When focus would leave, shouldYieldFocus(this)
        // decides; false restores focus via peer.focus(). Previous
        // listener is uninstalled on replace so swapping verifiers
        // doesn't stack dispatches.
        vaadinx.swing.InputVerifier old = this.inputVerifier;
        if (old == newVerifier) return;
        if (blurListenerRegistration != null) {
            com.vaadin.flow.shared.Registration stale = blurListenerRegistration;
            withPeer(p -> stale.remove());
            blurListenerRegistration = null;
        }
        this.inputVerifier = newVerifier;
        if (newVerifier != null && getPeer() instanceof com.vaadin.flow.component.BlurNotifier<?> bn) {
            com.vaadin.flow.shared.Registration[] registered = new com.vaadin.flow.shared.Registration[1];
            withPeer(p -> registered[0] = bn.addBlurListener(e ->
                    vaadinx.EHelper.callSwing(() -> {
                        // verify/shouldYieldFocus reads the component's
                        // state; false means the value is invalid and we
                        // restore focus. peer.focus() queues the refocus
                        // for the next browser round-trip.
                        if (!newVerifier.shouldYieldFocus(this)
                                && getPeer() instanceof com.vaadin.flow.component.Focusable<?> f) {
                            f.focus();
                        }
                    })));
            blurListenerRegistration = registered[0];
        }
        firePropertyChange("inputVerifier", old, newVerifier);
    }

    public vaadinx.swing.InputVerifier getInputVerifier() {
        return inputVerifier;
    }

