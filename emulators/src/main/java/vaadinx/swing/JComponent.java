    public final javax.swing.InputMap getInputMap(int condition) {
        // Lazy allocation: a component that never reads its InputMap
        // doesn't carry the allocation. Returning a live map that user
        // code can mutate is part of Swing's contract (idiomatic
        // `getInputMap().put(ks, key)` pattern), so we store-on-first-touch.
        return switch (condition) {
            case WHEN_FOCUSED -> {
                if (focusedInputMap == null) focusedInputMap = new javax.swing.InputMap();
                yield focusedInputMap;
            }
            case WHEN_ANCESTOR_OF_FOCUSED_COMPONENT -> {
                if (ancestorInputMap == null) ancestorInputMap = new javax.swing.InputMap();
                yield ancestorInputMap;
            }
            case WHEN_IN_FOCUSED_WINDOW -> {
                if (windowInputMap == null) windowInputMap = new javax.swing.InputMap();
                yield windowInputMap;
            }
            // JDK throws IllegalArgumentException for unknown conditions.
            // Match per R_match_swing_errors/D_never_fail_on_gaps — the never-fail rule scopes to incomplete
            // emulation, not input errors Swing itself rejects.
            default -> throw new IllegalArgumentException(
                    "condition must be one of WHEN_FOCUSED, WHEN_ANCESTOR_OF_FOCUSED_COMPONENT, WHEN_IN_FOCUSED_WINDOW");
        };
    }

