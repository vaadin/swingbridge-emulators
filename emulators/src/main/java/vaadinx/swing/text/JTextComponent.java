    public void setDocument(javax.swing.text.Document doc) {
        // Re-hook docToPeer across the swap so later edits still
        // mirror into the peer. Swing fires "document" PCE too.
        // Unhook first and re-hook after so the intermediate PCE
        // doesn't see a half-wired state. Push the new Document's
        // text to the peer so the UI reflects the swap immediately.
        javax.swing.text.Document old = this.document;
        if (old == doc) return;
        if (old != null) {
            old.removeDocumentListener(docToPeer);
        }
        this.document = doc;
        if (doc != null) {
            doc.addDocumentListener(docToPeer);
        }
        firePropertyChange("document", old, doc);
        if (doc != null) {
            onDocumentMutated();
        }
    }

