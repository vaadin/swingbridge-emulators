    /**
     * Installs {@code c} as the caret every caret and selection method goes through, and
     * fires {@code "caret"}. A {@link DefaultCaret} is installed fully: it follows the
     * Document from here on and the peer renders it. Any other {@code Caret} is used but
     * not installed — WARN — since {@link javax.swing.text.Caret#install} takes the JDK's
     * {@code JTextComponent}, which this class is not; one that does its setup there
     * starts uninitialised.
     */
    public void setCaret(javax.swing.text.Caret c) {
        if (caret != null) {
            caret.removeChangeListener(caretEvent);
            if (caret instanceof DefaultCaret dc) {
                dc.deinstall(this);
            }
        }
        javax.swing.text.Caret old = caret;
        caret = c;
        if (caret != null) {
            if (caret instanceof DefaultCaret dc) {
                dc.install(this);
            } else {
                vaadinx.EHelper.onUnimplemented("JTextComponent", "setCaret(install)", c);
            }
            caret.addChangeListener(caretEvent);
            caretListenersChanged();
        }
        firePropertyChange("caret", old, caret);
        if (old != null) {
            scheduleCaretRender();
        }
    }

