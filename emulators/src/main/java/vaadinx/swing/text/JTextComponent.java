    /**
     * Replaces the selection with {@code content} through the Document, so a filter sees
     * the edit; with nothing selected, inserts at the caret. The caret then follows the
     * edit under its update policy, as it follows any other.
     */
    public void replaceSelection(java.lang.String content) {
        javax.swing.text.Document doc = getDocument();
        if (doc != null) {
            try {
                boolean composedTextSaved = saveComposedText(caret.getDot());
                int p0 = Math.min(caret.getDot(), caret.getMark());
                int p1 = Math.max(caret.getDot(), caret.getMark());
                if (doc instanceof javax.swing.text.AbstractDocument) {
                    ((javax.swing.text.AbstractDocument) doc).replace(p0, p1 - p0, content, null);
                } else {
                    if (p0 != p1) {
                        doc.remove(p0, p1 - p0);
                    }
                    if (content != null && content.length() > 0) {
                        doc.insertString(p0, content, null);
                    }
                }
                if (composedTextSaved) {
                    restoreComposedText();
                }
            } catch (javax.swing.text.BadLocationException e) {
                // The JDK beeps (provideErrorFeedback); there is no beep to give.
            }
        }
    }

