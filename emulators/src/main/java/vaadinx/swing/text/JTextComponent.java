    /**
     * Mirror the peer's current value into the Document as the <em>edit</em> that
     * produced it, then let the Document have the last word.
     *
     * <p>Two properties, both of which a user-supplied {@code Document} depends on:
     *
     * <ul>
     *   <li><b>The Document sees a delta, not a wholesale replacement.</b> A filtering
     *       {@code PlainDocument} is written against per-keystroke inserts — it tests
     *       {@code getLength() + str.length()} against a cap, or branches on
     *       {@code str.equals(",")}. Handed the entire field value it either rejects
     *       an edit it would have allowed (capping the whole value, not the keystroke)
     *       or never takes its single-character branches at all.
     *   <li><b>The Document is authoritative.</b> After the edit, if the Document does
     *       not hold what the browser sent — a filter rejected the insert, capped it, or
     *       <em>rewrote</em> it (a thousands-separator formatter turning {@code 1234}
     *       into {@code 1,234}) — the Document's text is pushed back to the peer and the
     *       caret restored, so the browser shows what {@code getText()} would return.
     *       Swing has this for free: there, the field renders the Document.
     * </ul>
     *
     * <p>The Document mutation still fires events to user-registered DocumentListeners —
     * that's R_swing_is_truth's whole point. A rejection is ordinary filter behaviour, not an
     * incompleteness, so it does <em>not</em> WARN: the {@code BadLocationException} a
     * filter throws to refuse an edit is caught and answered by the push-back.
     */
    private void syncDocumentFromPeer(String peerValue) {
        if (preventPeerEvents) return;
        final String incoming = peerValue == null ? "" : peerValue;
        preventPeerEvents = true;
        try {
            applyPeerEdit(incoming);
        } catch (javax.swing.text.BadLocationException e) {
            // A filter refusing the edit. Nothing to report — the push-back below
            // reverts the browser, which is what refusal means.
        } finally {
            preventPeerEvents = false;
        }

        if (readDocument().equals(incoming)) {
            // The caret followed the edit as the Document dictates, and the browser's
            // own caret moved with the keystroke. Take them to agree; the browser's
            // next selection report corrects the caret where they do not.
            markCaretRendered();
        } else {
            // The filter changed or refused something: push the Document back, and the
            // caret with it — a reformatting filter moves it deliberately.
            onDocumentMutated();
        }
    }

    /**
     * Apply {@code incoming} to the Document as the single contiguous edit that turns
     * the Document's current text into it — the shape a keystroke, a delete or a paste
     * actually has. Derived from the common prefix and suffix, so an insert arrives as
     * an insert, a deletion as a remove, and a replacement as both.
     *
     * <p>Every pair of strings yields exactly one such edit, so there is no
     * "unrecognised change" case to fall back on. It need not be literally the
     * keystroke the user pressed (an IME commit or an autofill can collapse into one
     * edit that merely has the same effect) — what matters is that a filter sees an
     * edit of the right shape and size instead of the whole field.
     */
    private void applyPeerEdit(String incoming) throws javax.swing.text.BadLocationException {
        final String current = readDocument();
        if (current.equals(incoming)) return;

        final int shorter = Math.min(current.length(), incoming.length());
        int prefix = 0;
        while (prefix < shorter && current.charAt(prefix) == incoming.charAt(prefix)) prefix++;
        int suffix = 0;
        while (suffix < shorter - prefix
                && current.charAt(current.length() - 1 - suffix)
                        == incoming.charAt(incoming.length() - 1 - suffix)) {
            suffix++;
        }

        final int removeLen = current.length() - prefix - suffix;
        final String inserted = incoming.substring(prefix, incoming.length() - suffix);
        // Remove then insert, as Swing's own replace does — so a filter that overrides
        // only one of the two still sees its half. If insertString refuses, the removal
        // stands and the push-back syncs the browser to that state, again like Swing.
        if (removeLen > 0) document.remove(prefix, removeLen);
        if (!inserted.isEmpty()) document.insertString(prefix, inserted, null);
    }

