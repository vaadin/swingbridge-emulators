    /**
     * The JDK's {@code MutableCaretEvent}: relays the caret's change to this component's
     * {@code CaretListener}s, and schedules the render. While a drag is active the relay
     * holds the listeners back and fires once at its end, as the JDK does between a mouse
     * press and its release; here a drag is a browser report that moves both ends.
     */
    private final class CaretRelay implements javax.swing.event.ChangeListener {
        boolean dragActive;

        @Override
        public void stateChanged(javax.swing.event.ChangeEvent e) {
            scheduleCaretRender();
            if (!dragActive) {
                fire();
            }
        }

        void fire() {
            fireCaretUpdate(new com.vaadin.swingbridge.surrogates.swing.text.SCaretEvent(
                    JTextComponent.this, caret.getDot(), caret.getMark()));
        }
    }

