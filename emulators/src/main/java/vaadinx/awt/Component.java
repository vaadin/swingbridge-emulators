    /**
     * Whether {@code c} is a colour the theme owns rather than one the app asked
     * for — the discriminator of
     * <a href="../../../../../../emulators/decisions.md#D_theme_is_lookandfeel">D_theme_is_lookandfeel</a>.
     *
     * <p>Two kinds qualify, and both are the JDK's own vocabulary for "this is a
     * default":
     *
     * <ul>
     * <li>{@link javax.swing.plaf.UIResource} — what a L&amp;F installs, and what
     *     {@code LookAndFeel.installColorsAndFont} is willing to overwrite.
     * <li>{@link java.awt.SystemColor} — the AWT-era spelling of the same idea.
     *     It needs naming separately because it is {@code final} and cannot
     *     implement the marker, so {@code javac} rejects an {@code instanceof
     *     UIResource} test against it outright.
     * </ul>
     *
     * <p>Deliberately not value-equality against the table: a
     * {@code ColorUIResource} {@code equals} a plain {@code Color} of the same
     * RGB, so comparing values cannot tell a default from a migrator who really
     * did ask for {@code #EEEEEE}. The marker can.
     */
    protected static boolean isThemeDefault(java.awt.Color c) {
        return c instanceof javax.swing.plaf.UIResource || c instanceof java.awt.SystemColor;
    }

