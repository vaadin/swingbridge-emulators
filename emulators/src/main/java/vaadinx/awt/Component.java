    /**
     * Subscribes once to the peer's {@link com.vaadin.flow.component.FocusNotifier}
     * / {@link com.vaadin.flow.component.BlurNotifier} and fans the events out
     * over {@code listenerList} through {@link #processFocusEvent}, moving
     * {@code FocusTracker}'s pointer with them so a listener reading
     * {@code getFocusOwner()} inside its own callback sees itself.
     *
     * <p>One subscription drives the whole listener list (R_vaadin_first's shared wiring
     * shape), installed lazily because it costs a round trip per focus change
     * and most components have no focus listener. Dispatch goes through
     * {@link vaadinx.EHelper#callSwing} (R_callswing_envelope), so a listener that opens a modal
     * dialog can park.
     *
     * <p>Distinct from the focus pointer, and both are needed: this
     * delivers AWT events to <em>one component's</em> listeners, where
     * {@code FocusTracker}'s UI-wide {@code focusin} answers "who has focus"
     * for the whole tab — including peers this bridge cannot subscribe to.
     */
    private void installFocusBridge() {
        if (focusBridgeInstalled) return;
        focusBridgeInstalled = true;
        withPeer(p -> {
            if (p instanceof com.vaadin.flow.component.FocusNotifier<?> fn) {
                fn.addFocusListener(e -> vaadinx.EHelper.callSwing(() -> {
                    com.vaadin.swingbridge.surrogates.FocusTracker.noteFocusGained(getPeer());
                    processFocusEvent(new vaadinx.awt.event.FocusEvent(
                            this, vaadinx.awt.event.FocusEvent.FOCUS_GAINED));
                }));
            }
            if (p instanceof com.vaadin.flow.component.BlurNotifier<?> bn) {
                bn.addBlurListener(e -> vaadinx.EHelper.callSwing(() -> {
                    com.vaadin.swingbridge.surrogates.FocusTracker.noteFocusLost(getPeer());
                    processFocusEvent(new vaadinx.awt.event.FocusEvent(
                            this, vaadinx.awt.event.FocusEvent.FOCUS_LOST));
                }));
            }
        });
        if (!(peer instanceof com.vaadin.flow.component.FocusNotifier<?>)
                && !(peer instanceof com.vaadin.flow.component.BlurNotifier<?>)) {
            // Nothing in the browser can report focus for this peer, so a stored
            // listener would never fire. Say so rather than looking wired.
            vaadinx.EHelper.onUnimplemented(getClass().getSimpleName(),
                    "addFocusListener/non-focusable-peer");
        }
    }

