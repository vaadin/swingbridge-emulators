    public void setPreferredSize(java.awt.Dimension preferredSize) {
        java.awt.Dimension oldSize = this.preferredSize;
        this.preferredSize = preferredSize;
        // D_layout_owns_child_sizing: the pref lands as
        // `width: var(--emul-layout-w, Npx)` rather than a bare `width: Npx`,
        // because a preferred size means nothing until a parent layout rules on
        // it. AWT's child never sizes itself — layoutContainer does, and it
        // decides per axis whether the pref is consulted, clamped or ignored
        // (BorderLayout NORTH takes the container's width and only the pref
        // *height*; GridLayout ignores both). Writing a bare width hardcoded
        // FlowLayout's answer for every layout, which is how a NORTH toolbar
        // came to render at 850px inside a 1400px region.
        //
        // The var() indirection is what makes the two writes order-independent:
        // this setter may run before or after any number of layout passes, and
        // the layout's own policy write never has to touch `width` — so it can
        // never clobber a field surrogate's columns-derived width either.
        //
        // Zero / negative on an axis is treated as "leave this axis to
        // the layout" (clear the CSS rule) rather than as a hard
        // {@code width:0 / height:0} that collapses the element. The
        // common Swing idiom
        // {@code setPreferredSize(new Dimension(W, getPreferredSize().height))}
        // pulls through {@code getPreferredSize().height} which on our
        // emulator defaults to 0 (we don't measure fonts) — honoring
        // that as "auto height" matches the migrator's
        // lock-the-width-leave-the-height intent rather than rendering
        // a 0-tall box.
        //
        // The width also goes out as the element's intrinsic inline size, so a
        // parent sizing itself from content sees the pref even where the layout
        // stretches this child. That is AWT's preferredLayoutSize consulting a
        // CENTER child's pref: without it an `auto` EAST track was sized by
        // the stretched child's text instead (D_layout_pref_intrinsic). The
        // vertical axis has no such write, because CSS has no block-axis-only
        // size containment.
        withPeer(p -> {
            com.vaadin.flow.dom.Style style = p.getElement().getStyle();
            if (preferredSize != null) {
                if (preferredSize.width > 0) {
                    style.set("width", com.vaadin.swingbridge.surrogates.util.LayoutCss.prefWidth(
                            preferredSize.width + "px"));
                    style.set("contain", "inline-size");
                    style.set("contain-intrinsic-inline-size", preferredSize.width + "px");
                } else {
                    style.remove("width");
                    style.remove("contain");
                    style.remove("contain-intrinsic-inline-size");
                }
                if (preferredSize.height > 0) {
                    style.set("height", com.vaadin.swingbridge.surrogates.util.LayoutCss.prefHeight(
                            preferredSize.height + "px"));
                } else {
                    style.remove("height");
                }
            } else {
                style.remove("width");
                style.remove("contain");
                style.remove("contain-intrinsic-inline-size");
                style.remove("height");
            }
        });
        firePropertyChange("preferredSize", oldSize, preferredSize);
    }

