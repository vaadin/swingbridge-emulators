    public void removeNotify() {
        // Where the JDK destroys the native peer. Ours survives, so clearing
        // the bit that stood for its existence is the whole body — plus the
        // event the JDK fires on the same edge. Container overrides to
        // unrealise its children *before* chaining here, which is why the flag
        // flips bottom-up while the calls enter top-down (measured on JDK 25).
        // DEBUG log only; a realise/unrealise cycle fires once per Component,
        // which would swamp real warnings at INFO.
        vaadinx.EHelper.onNoop("Component", "removeNotify");
        displayable = false;
        fireDisplayabilityChanged();
    }

    public void addNotify() {
        // Where the JDK creates the native peer. Ours exists from the
        // constructor, so the bit is all that is left — set before Container's
        // child cascade runs, so a child's addNotify already sees its parent
        // displayable, as it does in AWT.
        vaadinx.EHelper.onNoop("Component", "addNotify");
        displayable = true;
        fireDisplayabilityChanged();
    }

    /**
     * The {@code DISPLAYABILITY_CHANGED} half of AWT's hierarchy-event surface,
     * fired on <em>this</em> component only. Deliberately not the recursive
     * {@link #fireHierarchyEvent} that {@code PARENT_CHANGED} uses: the
     * realise/unrealise cascade visits every descendant already, and each fires
     * its own event with {@code changed} set to itself — measured on JDK 25,
     * where a leaf's event reports {@code changed=leaf}, not {@code changed=}
     * the ancestor whose {@code addNotify()} started the cascade. Recursing
     * here would deliver one event per ancestor per descendant.
     */
    private void fireDisplayabilityChanged() {
        fireHierarchyEventSelf(
                vaadinx.awt.event.HierarchyEvent.HIERARCHY_CHANGED, this, parent,
                vaadinx.awt.event.HierarchyEvent.DISPLAYABILITY_CHANGED);
    }

