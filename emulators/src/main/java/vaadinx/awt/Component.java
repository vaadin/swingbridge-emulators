    /**
     * Subscribes once to the peer's DOM mouse events and fans them out over
     * {@code listenerList} through {@link #processMouseEvent}, mapping
     * {@code mousedown}/{@code mouseup}/{@code click}/{@code mouseenter}/{@code
     * mouseleave} onto AWT's {@code MOUSE_PRESSED}/{@code RELEASED}/{@code
     * CLICKED}/{@code ENTERED}/{@code EXITED}.
     *
     * <p>One set of subscriptions drives the whole listener list (R_vaadin_first's
     * shared wiring shape), installed lazily because each costs a round trip and
     * most components have no mouse listener. Dispatch goes through
     * {@link vaadinx.EHelper#callSwing} (R_callswing_envelope), so a listener
     * that opens a modal dialog can park — the migrated-app case this exists
     * for is a {@code JLabel} whose {@code mousePressed} navigates.
     *
     * <p><b>The browser is the state machine, not us.</b> AWT's ordering
     * (pressed → released → clicked), its "no {@code MOUSE_CLICKED} when the
     * release lands elsewhere", and its 1-then-2 click-count escalation are
     * all reproduced by forwarding the DOM's own events rather than
     * synthesising them: measured 2026-09-02, the DOM agrees with AWT on all
     * three. Two consequences that look like omissions and are not — a right
     * button fires no {@code click} at all in the DOM, hence no
     * {@code MOUSE_CLICKED}, and {@code isPopupTrigger()} rides the *press*
     * (AWT's X11 convention, likewise measured).
     * <p>No {@code preventPeerEvents} guard: nothing pushes a synthetic click
     * *down* to the peer, so this direction has no echo to suppress.
     * <p>Coordinates come from {@code clientX/Y} minus the host's own
     * bounding box, <b>not</b> {@code offsetX/Y} — the latter is relative to
     * the event *target*, and whether that is the peer host depends on the
     * boundary crossed: a shadow root retargets to the host, a slot or a
     * plain child does not. Vaadin mixes both (a {@code vaadin-button}
     * retargets, a {@code vaadin-text-field}'s slotted {@code <input>} does
     * not), so {@code offsetX} reads correct on one and ~10px wrong on the
     * other.
     */
    private void installMouseBridge() {
        if (mouseBridgeInstalled || mouseBridgeSuppressed) return;
        mouseBridgeInstalled = true;
        withPeer(p -> {
            subscribeMouse("mousedown", vaadinx.awt.event.MouseEvent.MOUSE_PRESSED);
            subscribeMouse("mouseup", vaadinx.awt.event.MouseEvent.MOUSE_RELEASED);
            subscribeMouse("click", vaadinx.awt.event.MouseEvent.MOUSE_CLICKED);
            subscribeMouse("mouseenter", vaadinx.awt.event.MouseEvent.MOUSE_ENTERED);
            subscribeMouse("mouseleave", vaadinx.awt.event.MouseEvent.MOUSE_EXITED);
        });
    }

    private void subscribeMouse(String domEvent, int awtId) {
        getPeer().getElement().addEventListener(domEvent, event -> {
            vaadinx.awt.event.MouseEvent me = toMouseEvent(event.getEventData(), awtId);
            vaadinx.EHelper.callSwing(() -> processMouseEvent(me));
        })
                .addEventData("event.clientX - element.getBoundingClientRect().left")
                .addEventData("event.clientY - element.getBoundingClientRect().top")
                .addEventData("event.clientX")
                .addEventData("event.clientY")
                .addEventData("event.button")
                .addEventData("event.detail")
                .addEventData("event.shiftKey")
                .addEventData("event.ctrlKey")
                .addEventData("event.altKey")
                .addEventData("event.metaKey");
    }

    /**
     * @param data the DOM event's collected {@code addEventData} payload; every
     *     field is read defensively, since a browser that reports none still has
     *     to produce a dispatchable event
     */
    private vaadinx.awt.event.MouseEvent toMouseEvent(
            tools.jackson.databind.JsonNode data, int awtId) {
        int x = jsonInt(data, "event.clientX - element.getBoundingClientRect().left");
        int y = jsonInt(data, "event.clientY - element.getBoundingClientRect().top");
        int xAbs = jsonInt(data, "event.clientX");
        int yAbs = jsonInt(data, "event.clientY");
        // DOM numbers buttons from 0 and orders them left/middle/right; AWT
        // numbers from 1 in the same order.
        int button = switch (jsonInt(data, "event.button")) {
            case 0 -> vaadinx.awt.event.MouseEvent.BUTTON1;
            case 1 -> vaadinx.awt.event.MouseEvent.BUTTON2;
            case 2 -> vaadinx.awt.event.MouseEvent.BUTTON3;
            default -> vaadinx.awt.event.MouseEvent.NOBUTTON;
        };
        // enter/leave carry detail 0, where AWT reports 0 for the same events.
        int clickCount = jsonInt(data, "event.detail");
        int modifiers = 0;
        if (jsonBool(data, "event.shiftKey")) modifiers |= vaadinx.awt.event.InputEvent.SHIFT_DOWN_MASK;
        if (jsonBool(data, "event.ctrlKey")) modifiers |= vaadinx.awt.event.InputEvent.CTRL_DOWN_MASK;
        if (jsonBool(data, "event.altKey")) modifiers |= vaadinx.awt.event.InputEvent.ALT_DOWN_MASK;
        if (jsonBool(data, "event.metaKey")) modifiers |= vaadinx.awt.event.InputEvent.META_DOWN_MASK;
        boolean popupTrigger = button == vaadinx.awt.event.MouseEvent.BUTTON3
                && awtId == vaadinx.awt.event.MouseEvent.MOUSE_PRESSED;
        return new vaadinx.awt.event.MouseEvent(this, awtId, System.currentTimeMillis(),
                modifiers, x, y, xAbs, yAbs, clickCount, popupTrigger, button);
    }

    private static int jsonInt(tools.jackson.databind.JsonNode data, String key) {
        return data == null || !data.has(key) ? 0 : (int) Math.round(data.get(key).asDouble(0));
    }

    private static boolean jsonBool(tools.jackson.databind.JsonNode data, String key) {
        return data != null && data.has(key) && data.get(key).asBoolean(false);
    }

