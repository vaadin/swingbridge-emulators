    public boolean isShowing() {
        // AWT's own body, ported: visible AND displayable AND the parent chain
        // is showing. The recursion is not optional — AWT never writes a
        // descendant's `visible` field, so hiding an intermediate container
        // leaves every child `visible == true` and only the derived answer
        // changes (measured on JDK 25: a leaf under a hidden JPanel reports
        // visible=true, showing=false). Reading displayability alone, as this
        // did while displayability meant Vaadin attachment, made such a leaf
        // claim it was showing.
        if (visible && displayable) {
            vaadinx.awt.Container p = parent;
            return p == null || p.isShowing();
        }
        return false;
    }

    /**
     * Whether this component's Swing {@code enabled} may be written through to
     * the Vaadin peer: true for a leaf, false once emulator children live inside
     * the peer element. Flow's disabled state cascades to the whole subtree and
     * Swing's does not, so a populated container must not push
     * (D_container_enabled_no_cascade). {@link Container} re-checks this on every
     * insertion, so a container disabled while empty does not trap the children
     * it gains later.
     */
    boolean pushesEnabledToPeer() {
        return !(this instanceof vaadinx.awt.Container c && c.getComponentCount() > 0);
    }

    public void setEnabled(boolean b) {
        // No PropertyChangeEvent here, deliberately: java.awt.Component.setEnabled
        // delegates to the deprecated enable(), which fires only the
        // AccessibleContext property — the bound "enabled" event is
        // JComponent's own override. Firing it at this level would give a
        // plain AWT Button/Label/Panel a callback the desktop never sends
        // (D_property_fanout_audit). JComponent.setEnabled fires it.
        if (!pushesEnabledToPeer()) {
            // Not onUnsupported: a container declining on purpose is not a peer
            // that cannot comply, and conflating them WARNs about no gap.
            // Recording is the whole emulation — a disabled Swing container
            // still fires every mouse callback, so gating anything here would
            // invent a behaviour Swing lacks (R_no_silent_improvements).
            this.enabled = b;
        } else if (peer instanceof com.vaadin.flow.component.HasEnabled he) {
            withPeer(p -> he.setEnabled(b));
            this.enabled = b;
        } else if (!b) {
            // Peer lacks HasEnabled — no DOM affordance for "disabled". Rather
            // than pretending we disabled it, warn and leave the field at true
            // so isEnabled() keeps telling callers the honest answer.
            vaadinx.EHelper.onUnsupported("Component", "setEnabled", b);
        }
        // else: non-HasEnabled peer, b=true — already effectively enabled, nothing to do.
    }

