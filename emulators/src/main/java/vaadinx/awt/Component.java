    // ---- Visibility -------------------------------------------------
    //
    // The JDK's arrow runs setVisible -> show(b) -> show() / hide(), with all
    // the work in the deprecated pair and setVisible a two-line delegation.
    // That looks backwards from a modern vantage point and is easy to "fix"
    // into the shape user code reads more often — but Window overrides show()
    // and hide(), not setVisible, so inverting it strands every Window
    // override and leaves nowhere for the JDK's show() -> addNotify() edge to
    // live. R_no_vaadin_in_api limb 2: keep the JDK's direction.

    public void setVisible(boolean b) {
        show(b);
    }

    public void show(boolean b) {
        if (b) {
            show();
        } else {
            hide();
        }
    }

    public void show() {
        // Guarded on the current state as the JDK's is — a redundant show()
        // must not re-push to the peer or re-fire.
        if (visible) return;
        visible = true;
        applyVisibleToPeer(true);
        // AWT signals visibility with a ComponentEvent and *only* a
        // ComponentEvent — there is no "visible" bound property on Component.
        // JPopupMenu is the sole class in java.awt/javax.swing that fires one
        // (R_decline_effect_only).
        fireComponentEvent(vaadinx.awt.event.ComponentEvent.COMPONENT_SHOWN);
    }

    /**
     * Where the JDK calls {@code peer.setVisible(...)} from {@link #show()} /
     * {@link #hide()}. Split out because a Window's peer is not simply shown
     * and hidden — it is attached to a route or opened as an overlay — so
     * {@link vaadinx.awt.Window} substitutes its own peer work here rather
     * than duplicating the surrounding state machine.
     *
     * <p>Every Vaadin Component has {@code setVisible}, so no {@code HasVisible}
     * check is needed (unlike {@code setEnabled}), and Vaadin's {@code false}
     * removes the element from the DOM — which is Swing's "invisible component
     * takes no space" contract.
     */
    protected void applyVisibleToPeer(boolean b) {
        withPeer(p -> p.setVisible(b));
    }

