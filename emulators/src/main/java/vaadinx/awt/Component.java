    // fire* helpers follow Container.fireContainerEvent's pattern: short-circuit
    // event allocation when nobody's listening, then route through the matching
    // process*Event method so user-overridden process methods still run. Kept
    // protected so JComponent subclasses (and later peer-wiring code) can
    // fire Component-level events from their own state-change points.
    //
    // Only the events wired today get helpers: ComponentEvent (from setVisible)
    // and HierarchyEvent (from Container add/remove). Focus/Key/Mouse/etc.
    // will get helpers when their peer listeners are wired — each fire
    // method naturally pairs with its one caller.

    protected void fireComponentEvent(int id) {
        if (listenerList.getListenerCount(vaadinx.awt.event.ComponentListener.class) == 0) return;
        processComponentEvent(new vaadinx.awt.event.ComponentEvent(this, id));
    }

    /**
     * Fires a {@link vaadinx.awt.event.HierarchyEvent} on this component.
     * Container overrides to also recurse into descendants — AWT semantics
     * for PARENT_CHANGED / DISPLAYABILITY_CHANGED / SHOWING_CHANGED, where
     * the entire reparented subtree observes the change.
     */
    protected void fireHierarchyEvent(int id, vaadinx.awt.Component changed,
                                      vaadinx.awt.Container changedParent, long flags) {
        fireHierarchyEventSelf(id, changed, changedParent, flags);
    }

    /**
     * {@link #fireHierarchyEvent} without Container's descendant recursion —
     * the seam for the flags AWT fires per-component rather than per-subtree.
     */
    final void fireHierarchyEventSelf(int id, vaadinx.awt.Component changed,
                                      vaadinx.awt.Container changedParent, long flags) {
        // HIERARCHY_CHANGED routes to HierarchyListener; ANCESTOR_MOVED/RESIZED
        // to HierarchyBoundsListener. Check both counts — we don't know which
        // listener type the caller's id is aimed at until we switch below.
        int hl = listenerList.getListenerCount(vaadinx.awt.event.HierarchyListener.class);
        int hbl = listenerList.getListenerCount(vaadinx.awt.event.HierarchyBoundsListener.class);
        if (hl == 0 && hbl == 0) return;
        vaadinx.awt.event.HierarchyEvent e = new vaadinx.awt.event.HierarchyEvent(this, id, changed, changedParent, flags);
        if (id == vaadinx.awt.event.HierarchyEvent.HIERARCHY_CHANGED) {
            processHierarchyEvent(e);
        } else {
            processHierarchyBoundsEvent(e);
        }
    }

    // AWT dispatch: each process* method switches on the event id and calls
    // exactly one listener method per stored listener. Split between process
    // methods mirrors AWT's own split (moved/dragged go to processMouseMotion,
    // not processMouse), so user code that overrides a specific process
    // method only sees the ids AWT would've routed to it. Ids outside a
    // method's range are dropped — AWT does the same, no default branch.
    //
    // Each method null-guards the event argument: AWT NPEs, we return silently.
    // Same precedent as contains(Point) / getListeners(Class) — smoke-test
    // null probe shouldn't crash on a method that has a trivial empty answer.

    protected void processComponentEvent(vaadinx.awt.event.ComponentEvent e) {
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.ComponentListener l : awtListeners(vaadinx.awt.event.ComponentListener.class)) {
            switch (id) {
                case vaadinx.awt.event.ComponentEvent.COMPONENT_MOVED -> l.componentMoved(e);
                case vaadinx.awt.event.ComponentEvent.COMPONENT_RESIZED -> l.componentResized(e);
                case vaadinx.awt.event.ComponentEvent.COMPONENT_SHOWN -> l.componentShown(e);
                case vaadinx.awt.event.ComponentEvent.COMPONENT_HIDDEN -> l.componentHidden(e);
                default -> { /* out-of-range id, drop — matches AWT */ }
            }
        }
    }

    protected void processFocusEvent(vaadinx.awt.event.FocusEvent e) {
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.FocusListener l : awtListeners(vaadinx.awt.event.FocusListener.class)) {
            switch (id) {
                case vaadinx.awt.event.FocusEvent.FOCUS_GAINED -> l.focusGained(e);
                case vaadinx.awt.event.FocusEvent.FOCUS_LOST -> l.focusLost(e);
                default -> { /* out-of-range id, drop */ }
            }
        }
    }

    protected void processKeyEvent(vaadinx.awt.event.KeyEvent e) {
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.KeyListener l : awtListeners(vaadinx.awt.event.KeyListener.class)) {
            switch (id) {
                case vaadinx.awt.event.KeyEvent.KEY_TYPED -> l.keyTyped(e);
                case vaadinx.awt.event.KeyEvent.KEY_PRESSED -> l.keyPressed(e);
                case vaadinx.awt.event.KeyEvent.KEY_RELEASED -> l.keyReleased(e);
                default -> { /* out-of-range id, drop */ }
            }
        }
    }

    protected void processMouseEvent(vaadinx.awt.event.MouseEvent e) {
        // AWT's processMouseEvent handles only the non-motion subset;
        // moved/dragged route to processMouseMotionEvent, wheel to
        // processMouseWheelEvent.
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.MouseListener l : awtListeners(vaadinx.awt.event.MouseListener.class)) {
            switch (id) {
                case vaadinx.awt.event.MouseEvent.MOUSE_PRESSED -> l.mousePressed(e);
                case vaadinx.awt.event.MouseEvent.MOUSE_RELEASED -> l.mouseReleased(e);
                case vaadinx.awt.event.MouseEvent.MOUSE_CLICKED -> l.mouseClicked(e);
                case vaadinx.awt.event.MouseEvent.MOUSE_ENTERED -> l.mouseEntered(e);
                case vaadinx.awt.event.MouseEvent.MOUSE_EXITED -> l.mouseExited(e);
                default -> { /* motion/wheel ids route to their own process methods */ }
            }
        }
    }

    protected void processMouseMotionEvent(vaadinx.awt.event.MouseEvent e) {
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.MouseMotionListener l : awtListeners(vaadinx.awt.event.MouseMotionListener.class)) {
            switch (id) {
                case vaadinx.awt.event.MouseEvent.MOUSE_MOVED -> l.mouseMoved(e);
                case vaadinx.awt.event.MouseEvent.MOUSE_DRAGGED -> l.mouseDragged(e);
                default -> { /* non-motion id, drop */ }
            }
        }
    }

    protected void processMouseWheelEvent(vaadinx.awt.event.MouseWheelEvent e) {
        // Only one id routes here (MOUSE_WHEEL), one callback — no switch needed.
        if (e == null) return;
        for (vaadinx.awt.event.MouseWheelListener l : awtListeners(vaadinx.awt.event.MouseWheelListener.class)) {
            l.mouseWheelMoved(e);
        }
    }

    protected void processInputMethodEvent(vaadinx.awt.event.InputMethodEvent e) {
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.InputMethodListener l : awtListeners(vaadinx.awt.event.InputMethodListener.class)) {
            switch (id) {
                case vaadinx.awt.event.InputMethodEvent.INPUT_METHOD_TEXT_CHANGED -> l.inputMethodTextChanged(e);
                case vaadinx.awt.event.InputMethodEvent.CARET_POSITION_CHANGED -> l.caretPositionChanged(e);
                default -> { /* out-of-range id, drop */ }
            }
        }
    }

    protected void processHierarchyEvent(vaadinx.awt.event.HierarchyEvent e) {
        // HierarchyListener is the narrow case — only HIERARCHY_CHANGED
        // reaches this method; ancestor-bounds ids go to processHierarchyBoundsEvent.
        if (e == null) return;
        for (vaadinx.awt.event.HierarchyListener l : awtListeners(vaadinx.awt.event.HierarchyListener.class)) {
            if (e.getID() == vaadinx.awt.event.HierarchyEvent.HIERARCHY_CHANGED) {
                l.hierarchyChanged(e);
            }
        }
    }

    protected void processHierarchyBoundsEvent(vaadinx.awt.event.HierarchyEvent e) {
        if (e == null) return;
        int id = e.getID();
        for (vaadinx.awt.event.HierarchyBoundsListener l : awtListeners(vaadinx.awt.event.HierarchyBoundsListener.class)) {
            switch (id) {
                case vaadinx.awt.event.HierarchyEvent.ANCESTOR_MOVED -> l.ancestorMoved(e);
                case vaadinx.awt.event.HierarchyEvent.ANCESTOR_RESIZED -> l.ancestorResized(e);
                default -> { /* HIERARCHY_CHANGED routes to processHierarchyEvent */ }
            }
        }
    }

