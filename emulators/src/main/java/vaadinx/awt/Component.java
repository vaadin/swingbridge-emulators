    /**
     * Push the current background to the peer, per D_theme_is_lookandfeel's
     * three-way rule. Split out of {@link #setBackground} because
     * {@code setOpaque} has to re-run exactly this decision: the gate is
     * two-directional, so neither setter can be the only one that evaluates it.
     *
     * <p>An app-set colour is written <em>inline</em>, which is what makes it
     * outrank the theme — the CSS cascade is the priority mechanism, so no
     * precedence machinery of our own is needed. A theme default writes nothing
     * here; the class-based default fill is a separate concern.
     */
    protected void applyBackgroundToPeer() {
        java.awt.Color c = this.background;
        boolean appSet = c != null && !isThemeDefault(c);
        // The theme-default row: a fill SB-Emulators supplies, so it goes to a class the
        // migrator can override rather than inline where they could not.
        String fill = defaultFillCssClass();
        boolean wantsDefault = c != null && isOpaque() && !appSet && fill != null;
        withPeer(p -> {
            if (appSet && isOpaque()) {
                p.getElement().getStyle().set("background-color", com.vaadin.swingbridge.surrogates.util.CssConvert.toCss(c));
            } else {
                p.getElement().getStyle().remove("background-color");
            }
            p.getElement().getClassList().set(FILL_DEFAULT, wantsDefault && FILL_DEFAULT.equals(fill));
            p.getElement().getClassList().set(FILL_CHROME, wantsDefault && FILL_CHROME.equals(fill));
        });
    }

    /** Opaque surface fill — Metal's flat {@code control} / {@code window}. */
    protected static final String FILL_DEFAULT = "emul-bg-default";

    /** Translucent chrome tint, for strips that read as raised against the page. */
    protected static final String FILL_CHROME = "emul-bg-chrome";

    /**
     * Which SB-Emulators-supplied fill this component takes when its background is an
     * L&amp;F default, or {@code null} when it needs none.
     *
     * <p>The answer is a property of the <em>peer</em>, not a list of class
     * names, so a new emulator inherits the right behaviour from the element it
     * peers on with nobody having to remember to add it:
     * {@link com.vaadin.flow.component.HtmlContainer} is Flow's base for plain
     * HTML elements that paint nothing of their own, so those fill; a themed
     * {@code vaadin-*} widget paints its own surface and needs no default.
     *
     * <p>Two peers escape the predicate and are named here rather than left to
     * be rediscovered. {@code Scroller} is not an {@code HtmlContainer} but is a
     * transparent overflow container, and both {@code JScrollPane} and
     * {@code java.awt.ScrollPane} are opaque under Metal. {@code MenuBar} the
     * predicate would exempt, but its host computes to fully transparent — so a
     * Swing menu bar would lose its chrome entirely — and it reads as a raised
     * strip rather than as page surface, hence the chrome tint.
     *
     * <p>Filling an inert peer — a {@code JViewport}, a {@code JScrollBar}, a
     * menu item's bookkeeping {@code Span} — needs no exemption: the element is
     * never rendered, so the fill is a no-op.
     */
    protected String defaultFillCssClass() {
        if (peer instanceof com.vaadin.flow.component.menubar.MenuBar) return FILL_CHROME;
        if (peer instanceof com.vaadin.flow.component.orderedlayout.Scroller) return FILL_DEFAULT;
        return peer instanceof com.vaadin.flow.component.HtmlContainer ? FILL_DEFAULT : null;
    }

    public java.awt.Font getFont() {
        // Local field → walk parents, like getForeground/getBackground — but the
        // root falls back to a non-null default instead of null. Real Swing
        // installs an L&F default font at construction, so getFont() is non-null
        // for a freshly-built JComponent; we run no L&F, so nothing sets the
        // field, and the walk would otherwise bottom out at null. Returning null
        // NPEs the GUI-builder idiom every NetBeans initComponents() emits:
        // comp.setFont(comp.getFont().deriveFont(comp.getFont().getStyle() |
        // BOLD, comp.getFont().getSize()-2)). isFontSet() still reports the
        // local-only truth (field != null). Font is shared with the surrogate
        // layer so a stage-2→stage-3 migration sees the same default.
        if (font != null) return font;
        if (parent != null) return parent.getFont();
        return com.vaadin.swingbridge.surrogates.util.CssConvert.DEFAULT_FONT;
    }

    public void setFont(java.awt.Font f) {
        // Four separate font-* properties rather than the `font` shorthand —
        // individual props compose with theme overrides better than the shorthand,
        // which resets every sub-property it doesn't list.
        java.awt.Font oldFont = this.font;
        this.font = f;
        withPeer(p -> {
            com.vaadin.flow.dom.Style style = p.getElement().getStyle();
            if (f != null) {
                style.set("font-family", com.vaadin.swingbridge.surrogates.util.CssConvert.toCssFontFamily(f));
                style.set("font-size", f.getSize() + "px");
                style.set("font-weight", f.isBold() ? "bold" : "normal");
                style.set("font-style", f.isItalic() ? "italic" : "normal");
            } else {
                style.remove("font-family");
                style.remove("font-size");
                style.remove("font-weight");
                style.remove("font-style");
            }
        });
        firePropertyChange("font", oldFont, f);
    }

