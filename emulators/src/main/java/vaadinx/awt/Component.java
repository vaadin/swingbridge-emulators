    public void revalidate() {
        // AWT: invalidate self, walk up to the nearest validate-root ancestor
        // (or the top of the tree if none), validate it. Each leg is mostly a
        // no-op today — Vaadin re-lays out on DOM change per R_layouts_close_enough, Container's
        // invalidate only forwards to LayoutManager2.invalidateLayout — but we
        // preserve the dispatch so user-overridden validate/invalidate/
        // isValidateRoot see the right calls (R_swing_is_truth), and so LayoutManager2
        // impls get their invalidateLayout when they land.
        synchronized (getTreeLock()) {
            invalidate();
            vaadinx.awt.Container root = parent;
            if (root == null) {
                // Orphan — AWT validates self in place of any ancestor walk.
                validate();
                return;
            }
            while (!root.isValidateRoot()) {
                vaadinx.awt.Container up = root.parent;
                if (up == null) break;  // hit the top without finding a validate-root
                root = up;
            }
            root.validate();
        }
    }

