    protected void processContainerEvent(vaadinx.awt.event.ContainerEvent e) {
        // AWT dispatches to one of two listener methods based on the event id.
        // We don't route through processEvent(AWTEvent) because our dispatch
        // path skips Toolkit/EventQueue entirely (D_own_awt_package — no java.desktop
        // runtime); fireContainerEvent calls us directly.
        int id = e.getID();
        for (vaadinx.awt.event.ContainerListener l : awtListeners(vaadinx.awt.event.ContainerListener.class)) {
            if (id == vaadinx.awt.event.ContainerEvent.COMPONENT_ADDED) {
                l.componentAdded(e);
            } else if (id == vaadinx.awt.event.ContainerEvent.COMPONENT_REMOVED) {
                l.componentRemoved(e);
            }
        }
    }

    protected void processEvent(java.awt.AWTEvent e) {
        if (e instanceof vaadinx.awt.event.ContainerEvent) {
            processContainerEvent((vaadinx.awt.event.ContainerEvent)e);
            return;
        }
        super.processEvent(e);
    }

