    protected void addImpl(vaadinx.awt.Component comp, java.lang.Object constraints, int index) {
        // The single choke point: the five add(...) overloads all funnel here, so
        // subclasses override only this method to intercept every insertion path.

        // Reject the same misuses AWT rejects — D_never_fail_on_gaps only suppresses failures
        // caused by incomplete emulation, not programming errors Swing itself
        // catches. Guard *order* is AWT's, not ours to tidy: the bounds check
        // runs first, so add(this, 999) reports the bad position rather than
        // the bad component, exactly as java.awt.Container does.
        if (index < -1 || index > components.size()) {
            throw new IllegalArgumentException("illegal component position");
        }
        checkAddToSelf(comp);
        checkNotAWindow(comp);

        // Detach from previous parent first. AWT does the same — reparenting a
        // component without an intermediate remove() is legal and common.
        if (comp.parent != null) {
            comp.parent.remove(comp);
            // AWT re-checks after the detach and *throws* rather than clamping:
            // if comp was our own child, its removal shrank the list and an
            // old-end index now points past the new end. Clamping instead would
            // silently accept a position AWT rejects (R_match_swing_errors).
            if (index > components.size()) {
                throw new IllegalArgumentException("illegal component position");
            }
        } else if (comp.displayable) {
            // No AWT counterpart, because AWT cannot reach this state: outside
            // Windows, displayability implies a parent that would have just
            // unrealised it. SB-Emulators can — an emulator added straight to a vanilla
            // Vaadin layout is a realisation root (Component.onPeerAttached),
            // displayable with no parent. Unrealise it here, exactly as the
            // reparent above would have, so that the addNotify below is its
            // first and not its second.
            comp.removeNotify();
        }

        int insertAt = index == -1 ? components.size() : index;
        components.add(insertAt, comp);
        comp.parent = this;
        releasePeerDisableForNewChild();

        // Mirror into the peer DOM. peerContentElement() lets subclasses redirect
        // children into a peer-internal content slot without overriding addImpl.
        withPeer(p -> peerContentElement().insertChild(insertAt, comp.getPeer().getElement()));

        // AWT's `if (peer != null) comp.addNotify()`: a component added to an
        // already-displayable container is realised on the spot, subtree and
        // all. Guarded on *our* displayability only, as the JDK guards it —
        // in AWT the child cannot already be displayable here, since the
        // reparent above unrealised it. The parent link is set *before* the
        // DOM insert, so the Vaadin attach that insert triggers already sees a
        // non-null parent and stands down (Component.onPeerAttached) — leaving
        // this the single realisation path, in AWT's order, rather than a race
        // with it.
        if (displayable) {
            comp.addNotify();
        }

        // AWT: notify the layout manager with the constraint object. R_infra_not_surface — we
        // keep this call shape even while layoutMgr is null in practice, so
        // real managers plug in without touching every call site. The
        // LayoutManager2 branch gets arbitrary constraints; the plain
        // LayoutManager branch only accepts String constraints (that's the
        // whole reason LayoutManager2 was introduced).
        if (layoutMgr != null) {
            if (layoutMgr instanceof vaadinx.awt.LayoutManager2 lm2) {
                lm2.addLayoutComponent(comp, constraints);
            } else if (constraints instanceof java.lang.String s) {
                layoutMgr.addLayoutComponent(s, comp);
            }
        }

        // Fire COMPONENT_ADDED last, after the child is fully linked and the
        // layout manager knows about it — matches AWT's ordering so a
        // listener can e.g. call container.validate() and get a correct tree.
        // Deliberately not fired from setComponentZOrder: AWT documents that
        // method as specifically skipping the event (that's its whole reason
        // for existing alongside add(comp, index)).
        fireContainerEvent(vaadinx.awt.event.ContainerEvent.COMPONENT_ADDED, comp);
        // AWT also fires HIERARCHY_CHANGED(PARENT_CHANGED) on the added
        // subtree — each descendant's HierarchyListeners see it, with
        // changedParent set to the new parent (this).
        comp.fireHierarchyEvent(
                vaadinx.awt.event.HierarchyEvent.HIERARCHY_CHANGED,
                comp, this, vaadinx.awt.event.HierarchyEvent.PARENT_CHANGED);
    }

