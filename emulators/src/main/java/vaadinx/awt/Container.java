    public boolean isAncestorOf(vaadinx.awt.Component c) {
        if (c == null) return false;
        vaadinx.awt.Container p = c.getParent();
        while (p != null) {
            if (p == this) return true;
            p = p.getParent();
        }
        return false;
    }

