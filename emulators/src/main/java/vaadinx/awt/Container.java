    public void setComponentZOrder(vaadinx.awt.Component comp, int index) {
        // AWT's setComponentZOrder: reorder an existing child, or reparent a
        // component from another container, skipping ContainerListener events
        // (that's the whole reason it exists alongside add(comp, index)). We
        // don't fire ContainerEvents (D_event_port_policy — ContainerEvent needs a
        // java.awt.Component source we can't supply), so the distinction from
        // add(comp, index) is moot for us except for the intra-container
        // reorder case, which add() doesn't express.
        if (comp == null) throw new NullPointerException("illegal null argument");
        if (comp == this) throw new IllegalArgumentException("component and container cannot be the same");
        if (comp instanceof vaadinx.awt.Container c && c.isAncestorOf(this)) {
            throw new IllegalArgumentException("component and container are ancestors of each other");
        }
        // Bound check: for an intra-container move the list size stays the
        // same, so valid final positions are 0..size-1. AWT's own check is
        // looser (allows index == size) but then ArrayList.add blows up, so we
        // tighten it here — same spirit as D_never_fail_on_gaps (match Swing's failure modes,
        // but on clearly-invalid inputs).
        if (index < 0 || index >= components.size()) {
            throw new IllegalArgumentException("illegal component position " + index + " should be >=0 and <" + components.size());
        }

        int oldIndex = components.indexOf(comp);
        if (oldIndex < 0) {
            // Different-parent reparent. AWT handles it; current slice doesn't
            // need it (R_infra_not_surface). Flagged so an actual caller surfaces instead of
            // silently doing the wrong thing.
            vaadinx.EHelper.onUnimplemented("Container", "setComponentZOrder(reparent)", comp, index);
            return;
        }
        if (oldIndex == index) return;

        // AWT semantics: `index` is the position in the *post-removal* list.
        // Remove first, then add at `index` — no pre-adjustment. Moving index 0
        // to index 2 in [a,b,c] gives [b,c,a], not [b,a,c]. The peer DOM
        // mirrors this; insertChild auto-detaches same-parent children.
        components.remove(oldIndex);
        components.add(index, comp);
        withPeer(p -> peerContentElement().insertChild(index, comp.getPeer().getElement()));
    }

    public void setLayout(vaadinx.awt.LayoutManager mgr) {
        // AWT: stores the manager and invalidates so next validate re-lays out.
        // Our invalidate() is a no-op at the Component level (R_layouts_close_enough — Vaadin
        // re-lays on DOM change), but we still fire the call so LayoutManager2
        // gets its invalidateLayout() notification per R_infra_not_surface/R_swing_is_truth.
        //
        // We deliberately do NOT lay out here — AWT's setLayout only invalidates,
        // and the "user code calls revalidate() after mutating layout state" quirk
        // is emulated rather than fixed (see FlowLayout.setAlignment). But the
        // outgoing manager's container CSS is dropped, because the browser makes
        // the un-revalidated interval visible in a way Swing never does: stale
        // display:flex over children already carrying the new manager's grid-area
        // renders scrambled, where clearing it renders a coherent block flow.
        // Only when a manager is actually being replaced — a first setLayout (every
        // ctor's) has nothing of ours on the element yet.
        if (this.layoutMgr != null && this.layoutMgr != mgr) {
            withPeer(p -> vaadinx.EHelper.resetContainerCss(peerContentElement()));
        }
        this.layoutMgr = mgr;
        warnedCustomLayout = false; // re-arm the Option-A WARN for the new manager
        invalidate();
    }

