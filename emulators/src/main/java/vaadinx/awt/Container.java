    public void doLayout() {
        // AWT: hand off to the installed LayoutManager. Under D_layout_css_on_content this is
        // where container-wide CSS gets written (BorderLayout → display:grid,
        // FlowLayout → display:flex, …). No manager installed → stay silent:
        // the container has no layout declared, children render as browser
        // defaults under the peer's own CSS.
        if (layoutMgr == null) {
            // No manager rules on the children, so each child's own preferred size
            // does — the "child owns both axes" policy of D_layout_owns_child_sizing.
            // Written rather than left absent for the two reasons sizingCss states:
            // it clears a previous manager's policy after setLayout(null), and it
            // stops a child from inheriting an ancestor's `auto` (this is the very
            // shape that does it — an absolute-layout panel sitting in a
            // BorderLayout region, its children carrying pref sizes).
            applyChildSizingPolicy(false, false);
            super.doLayout();
            return;
        }
        if (!(layoutMgr instanceof vaadinx.awt.CssEmittingLayoutManager)) {
            // The M1D_custom_layoutmanager fallback: a hand-rolled pixel
            // LayoutManager with no CSS translation. WARN once and fall back to
            // a readable vertical stack rather than leaving children in the
            // peer's default flow — Swing itself doesn't throw here (R_layouts_close_enough), so we
            // don't either. A migrator who needs faithful placement implements
            // CssEmittingLayoutManager instead.
            if (!warnedCustomLayout) {
                vaadinx.EHelper.onUnimplemented("vaadinx.awt.Container",
                        "setLayout(custom LayoutManager — no CSS translation, vertical fallback)",
                        layoutMgr.getClass().getName());
                warnedCustomLayout = true;
            }
            withPeer(p -> vaadinx.EHelper.applyContainerCss(peerContentElement(), "CustomLayoutFallback",
                    com.vaadin.swingbridge.surrogates.util.LayoutCss.verticalFallbackCss()));
            // The real manager's per-axis opinion is unreadable (that is why we are
            // in the fallback at all), so leave each child at its preferred size
            // rather than guessing — and write the policy, since the fallback may
            // have replaced a manager whose policy is still on the children
            // (D_layout_owns_child_sizing).
            applyChildSizingPolicy(false, false);
        }
        // Still notify the manager (R_infra_not_surface/R_swing_is_truth — AWT's doLayout always calls it): for
        // a CssEmittingLayoutManager this is where the CSS is emitted; for a
        // custom one it's a harmless best-effort setBounds pass over the fallback.
        layoutMgr.layoutContainer(this);
    }

    /**
     * Write the same {@code D_layout_owns_child_sizing} axis policy onto every child —
     * the manager-less counterpart to a {@code CssEmittingLayoutManager}'s per-child
     * {@code childCss}, used by the two paths in {@link #doLayout} that have no
     * translatable manager to ask.
     */
    private void applyChildSizingPolicy(boolean layoutSizesWidth, boolean layoutSizesHeight) {
        java.util.Map<String, String> css =
                com.vaadin.swingbridge.surrogates.util.LayoutCss.sizingCss(layoutSizesWidth, layoutSizesHeight);
        withPeer(p -> {
            for (vaadinx.awt.Component child : components) {
                vaadinx.EHelper.applyChildCss(child.getPeer().getElement(), css);
            }
        });
    }

